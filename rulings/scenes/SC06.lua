local A=__dofile("assessment_scenes/common.lua")
return A.register("SC06",function(room,attacker,target)
  A.actor(attacker,"luxun","lianying")
  local axe=A.equip(attacker,"axe")
  local slash=A.give(attacker,"slash",Card.Spade,7)
  local cost1=A.give(attacker,"peach",Card.Heart,3)
  local cost2=A.give(attacker,"peach",Card.Diamond,4)
  local jink=A.give(target,"jink",Card.Heart,2)
  local draw=room:printCard("jink",Card.Diamond,11)
  FkTest.runInRoom(function() room:moveCardTo(draw,Card.DrawPile) end)
  FkTest.setNextReplies(target,{FkTest.ReplyCard(jink)})
  FkTest.setNextReplies(attacker,{FkTest.ReplyDiscard({cost1.id,cost2.id}),"1"})
  FkTest.runInRoom(function() room:useCard{from=attacker,tos={target},card=slash} end)
  A.eq(target.hp,3,"贯石斧令已被闪抵消的杀继续造成伤害")
  A.eq(attacker:getCardIds("h"),{draw.id},"弃尽两张手牌后连营取得固定牌堆顶牌")
  A.eq(room:getCardArea(axe),Card.PlayerEquip,"贯石斧本体仍在装备区")
  A.finish("弃两张剩余手牌发动贯石斧后，连营可摸一张牌，随后该杀继续生效造成伤害；武器本身保留。")
end)
