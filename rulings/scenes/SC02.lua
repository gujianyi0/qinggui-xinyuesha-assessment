local A=__dofile("assessment_scenes/common.lua")
return A.register("SC02",function(room,attacker,target,retrial)
  A.actor(attacker,"lvbu","wushuang")
  A.actor(retrial,"simayi","guicai")
  A.equip(target,"eight_diagram")
  local red=A.give(retrial,"peach",Card.Heart,3)
  FkTest.runInRoom(function()
    room:moveCardTo(room:printCard("slash",Card.Heart,5),Card.DrawPile)
    room:moveCardTo(room:printCard("slash",Card.Spade,6),Card.DrawPile)
  end)
  FkTest.setNextReplies(target,{"1","1"})
  FkTest.setNextReplies(retrial,{FkTest.ReplyChooseCards({red.id})})
  FkTest.runInRoom(function() room:useCard{from=attacker,tos={target},card=Fk:cloneCard("slash")} end)
  A.eq(target.hp,4,"两次八卦响应成功满足无双要求")
  A.eq(retrial:isKongcheng(),true,"鬼才已使用指定红色手牌改判")
  local judgments=0
  for _,event in ipairs(A.trace.events) do if event.event=="fk.FinishJudge" then judgments=judgments+1 end end
  A.eq(judgments,2,"无双之杀实际进行了两次八卦判定")
  A.finish("无双要求两张闪，八卦可分别判定。固定牌堆中第一次黑判由鬼才改红，第二次为红，两次均成功，目标不受伤。")
end)
