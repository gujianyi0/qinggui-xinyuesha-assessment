local A=__dofile("assessment_scenes/common.lua")
return A.register("SC04V",function(room,attacker,first,second)
  A.equip(attacker,"qinggang_sword")
  A.equip(first,"vine")
  A.equip(second,"silver_lion")
  A.chain(first,second)
  FkTest.runInRoom(function()
    room:useCard{from=attacker,tos={first},card=Fk:cloneCard("fire__slash")}
  end)
  A.eq(first.hp,3,"未饮酒火杀无视首目标藤甲，造成1点")
  A.eq(second.hp,3,"连环白银狮子仍生效，此次传导为1点")
  A.eq(first:getMark(MarkEnum.MarkArmorNullified),0,"首目标藤甲无效标记已清理")
  A.eq(second:getMark(MarkEnum.MarkArmorNullified),0,"传导目标未残留青釭标记")
  A.finish("未饮酒且首目标藤甲、传导目标白银狮子时，青釭仅无视首目标防具；两者各受1点火焰伤害。")
end)
