local A=__dofile("assessment_scenes/common.lua")
return A.register("SC07",function(room,attacker,first,second)
  A.actor(first,"caocao","jianxiong")
  A.actor(second,"caocao","jianxiong")
  A.chain(first,second)
  local fire=A.give(attacker,"fire__slash",Card.Heart,7)
  FkTest.setNextReplies(first,{"__cancel","1"})
  FkTest.setNextReplies(second,{"1"})
  FkTest.runInRoom(function() room:useCard{from=attacker,tos={first},card=fire} end)
  A.eq(first.hp,3,"首目标曹操受1点火焰伤害")
  A.eq(second.hp,3,"实体牌移走后连环传导仍造成1点")
  A.eq(table.contains(first:getCardIds("h"),fire.id),true,"首目标奸雄获得造成伤害的实体牌")
  A.eq(table.contains(second:getCardIds("h"),fire.id),false,"传导目标无法再取得已离开处理区的牌")
  A.finish("首目标曹操发动奸雄取得实体火杀，不阻止连环伤害继续；后续曹操因牌已不在处理区，不能再次获得该牌。")
end)
